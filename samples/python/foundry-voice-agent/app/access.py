"""Bounded, single-process demo access. Never logs credentials, cookies or request bodies."""

import asyncio
import hashlib
import hmac
import re
import secrets
import time
from collections import deque
from dataclasses import dataclass, field

COOKIE = "__Host-webiq_session"
LOGIN_COOKIE = "__Host-webiq_login"
SESSION_SECONDS = 3600
MAX_LOGINS = 128


def parse_verifier(value: str) -> tuple[bytes, bytes]:
    if not re.fullmatch(r"scrypt\$[0-9a-f]{32}\$[0-9a-f]{64}", value):
        raise ValueError("DEMO_AUTH_VERIFIER must be generated by python -m app.setup_access.")
    _, salt, digest = value.split("$")
    return bytes.fromhex(salt), bytes.fromhex(digest)


def derive(passphrase: str, salt: bytes) -> bytes:
    return hashlib.scrypt(passphrase.encode("utf-8"), salt=salt, n=16384, r=8, p=1, dklen=32)


def make_verifier(passphrase: str) -> str:
    salt = secrets.token_bytes(16)
    return f"scrypt${salt.hex()}${derive(passphrase, salt).hex()}"


@dataclass
class Login:
    subject: str
    expires: float
    csrf: str = field(default_factory=lambda: secrets.token_urlsafe(32), repr=False)
    revoked: asyncio.Event = field(default_factory=asyncio.Event, repr=False)


class Access:
    def __init__(self, verifier: str, *, clock=time.monotonic):
        self.salt, self.digest = parse_verifier(verifier)
        self.clock = clock
        self.logins: dict[str, Login] = {}
        self.attempts: deque[float] = deque()
        self.peers: dict[str, deque[float]] = {}
        self.verifying = 0

    def _prune(self) -> None:
        now = self.clock()
        for key, login in list(self.logins.items()):
            if login.expires <= now:
                login.revoked.set()
                del self.logins[key]
        while self.attempts and now - self.attempts[0] >= 60:
            self.attempts.popleft()
        for peer, stamps in list(self.peers.items()):
            while stamps and now - stamps[0] >= 60:
                stamps.popleft()
            if not stamps:
                del self.peers[peer]

    def lookup(self, token: str | None) -> Login | None:
        self._prune()
        if not token or not re.fullmatch(r"[A-Za-z0-9_-]{43}", token):
            return None
        return self.logins.get(hashlib.sha256(token.encode()).hexdigest())

    def revoke(self, token: str | None) -> None:
        login = self.lookup(token)
        if login:
            login.revoked.set()
            del self.logins[login.subject]

    def revoke_all(self) -> None:
        for login in self.logins.values():
            login.revoked.set()
        self.logins.clear()

    async def authenticate(self, passphrase: str, peer: str) -> tuple[str, str | None]:
        self._prune()
        now = self.clock()
        # Trust only the transport peer, never client-supplied forwarded IP headers.
        peer_key = hashlib.sha256(peer.encode()).hexdigest()
        stamps = self.peers.get(peer_key, deque())
        if len(self.attempts) >= 30 or len(stamps) >= 10 or self.verifying >= 2:
            return "limited", None
        self.attempts.append(now)
        stamps.append(now)
        self.peers[peer_key] = stamps
        if len(self.logins) >= MAX_LOGINS:
            return "limited", None
        self.verifying += 1
        work = asyncio.create_task(asyncio.to_thread(derive, passphrase, self.salt))
        try:
            result = await asyncio.shield(work)
            if not hmac.compare_digest(result, self.digest):
                return "invalid", None
            # Another verifier may have completed while this one awaited.
            if len(self.logins) >= MAX_LOGINS:
                return "limited", None
            token = secrets.token_urlsafe(32)
            subject = hashlib.sha256(token.encode()).hexdigest()
            self.logins[subject] = Login(subject, self.clock() + SESSION_SECONDS)
            return "ok", token
        finally:
            # Cancelling a request does not stop its CPU worker. Hold its slot until it finishes.
            if work.done():
                self.verifying -= 1
            else:
                work.add_done_callback(lambda _: self._verification_finished())

    def _verification_finished(self) -> None:
        self.verifying -= 1
